_EE_SITE: _SiteFrame = _SiteFrame(
    (0.012, -0.000218, -0.098127), (1.0, 0.0, 1.0, 0.0)
)


def chain_constants() -> list[
    tuple[
        str,
        tuple[float, float, float],
        tuple[float, float, float, float],
        tuple[float, float],
    ]
]:
    """Expose the hardcoded chain for ``scripts/gen_so101_kinematics.py --check``."""
    return [(jf.name, jf.pos, jf.quat, jf.joint_range) for jf in _CHAIN]


def ee_site_constants() -> (
    tuple[tuple[float, float, float], tuple[float, float, float, float]]
):
    """Expose the hardcoded EE site frame for the generator's ``--check``."""
    return (_EE_SITE.pos, _EE_SITE.quat)


class UnreachablePoseError(ValueError):
    """Raised when :func:`solve_ik` cannot reach a target within tolerance.

    FR-SIM-17: IK must never silently return a clipped/best-effort
    configuration for a pose outside the workspace; callers get a typed
    error instead.
    """


@dataclass(frozen=True)
class IKResult:
    """Outcome of an inverse-kinematics solve (FR-SIM-17)."""

    q: npt.NDArray[np.float64]
    reachable: bool
    position_error_m: float


def _quat_to_rotation_matrix(
    quat: tuple[float, float, float, float],
) -> npt.NDArray[np.float64]:
    """Convert a MuJoCo-convention ``(w, x, y, z)`` quaternion to a 3x3
    rotation matrix. Not required to be unit norm (normalized here, same
    as MuJoCo's own compiler behavior)."""
    w, x, y, z = quat
    n = float(np.sqrt(w * w + x * x + y * y + z * z))
    w, x, y, z = w / n, x / n, y / n, z / n
    return np.array(
        [
            [
                1 - 2 * (y * y + z * z),
                2 * (x * y - z * w),
                2 * (x * z + y * w),
            ],
            [
                2 * (x * y + z * w),
                1 - 2 * (x * x + z * z),
                2 * (y * z - x * w),
            ],
            [
                2 * (x * z - y * w),
                2 * (y * z + x * w),
                1 - 2 * (x * x + y * y),
            ],
        ],
        dtype=np.float64,
    )


def _fixed_transform(
    pos: tuple[float, float, float],
    quat: tuple[float, float, float, float],
) -> npt.NDArray[np.float64]:
    T = np.eye(4, dtype=np.float64)
    T[:3, :3] = _quat_to_rotation_matrix(quat)
    T[:3, 3] = pos
    return T


def _rotate_z(theta: float) -> npt.NDArray[np.float64]:
    c, s = float(np.cos(theta)), float(np.sin(theta))
    T = np.eye(4, dtype=np.float64)
    T[0, 0] = c
    T[0, 1] = -s
    T[1, 0] = s
    T[1, 1] = c
    return T


def forward_kinematics_matrix(
    joint_positions: npt.NDArray[np.float64],
) -> npt.NDArray[np.float64]:
    """Return the 4x4 ``gripperframe`` site pose in the world frame.

    Pure NumPy, no ``mujoco`` import (FR-SIM-16). ``joint_positions`` has
    shape ``(5,)`` in :data:`_JOINT_NAMES` order.
    """
    q = np.asarray(joint_positions, dtype=np.float64).reshape(5)
    T = np.eye(4, dtype=np.float64)
    for jf, qi in zip(_CHAIN, q):
        T = T @ _fixed_transform(jf.pos, jf.quat) @ _rotate_z(float(qi))
    T = T @ _fixed_transform(_EE_SITE.pos, _EE_SITE.quat)
    return T


def _numerical_jacobian(
    joint_positions: npt.NDArray[np.float64],
) -> npt.NDArray[np.float64]:
    """Finite-difference geometric Jacobian ``(6, 5)`` at ``joint_positions``.

    Validated against MuJoCo ``mj_jacSite`` in tests only (never imported
    here); see ``docs/hardware/arm-selection.md`` design notes.
    """
    q = np.asarray(joint_positions, dtype=np.float64).reshape(5)
    T0 = forward_kinematics_matrix(q)
    p0 = T0[:3, 3]
    R0 = T0[:3, :3]
    J = np.zeros((6, 5), dtype=np.float64)
    for i in range(5):
        dq = q.copy()
        dq[i] += _FD_EPS
        T1 = forward_kinematics_matrix(dq)
        J[:3, i] = (T1[:3, 3] - p0) / _FD_EPS
        # Angular velocity from the relative rotation R0^T R1 (small-angle).
        dR = R0.T @ T1[:3, :3]
        J[3, i] = (dR[2, 1] - dR[1, 2]) / (2.0 * _FD_EPS)
        J[4, i] = (dR[0, 2] - dR[2, 0]) / (2.0 * _FD_EPS)
        J[5, i] = (dR[1, 0] - dR[0, 1]) / (2.0 * _FD_EPS)
    return J


def joint_limits_array() -> npt.NDArray[np.float64]:
    """Return the ``(5, 2)`` ``[lower, upper]`` joint-limit array."""
    return np.array([jf.joint_range for jf in _CHAIN], dtype=np.float64)


def solve_ik(
    target_xyz: npt.NDArray[np.float64],
    seed: npt.NDArray[np.float64] | None = None,
    *,
    tol_m: float = _IK_TOL_M,
    max_iters: int = _MAX_IK_ITERS,
) -> IKResult:
    """Damped least-squares position IK (FR-SIM-17).

    Args:
        target_xyz: Target end-effector position, shape ``(3,)``.
        seed: Initial joint configuration; defaults to the mid-range pose.
        tol_m: Position tolerance [m] to call the result reachable.
        max_iters: Iteration budget.

    Returns:
        An :class:`IKResult`. ``reachable`` is ``False`` (and ``q`` is the
        last iterate, provided only for diagnostics, never clipped to look
        plausible) when the solve does not converge within ``tol_m``.
    """
    limits = joint_limits_array()
    q = (
        np.asarray(seed, dtype=np.float64).reshape(5)
        if seed is not None
        else limits.mean(axis=1)
    )
    q = np.clip(q, limits[:, 0], limits[:, 1])
    target = np.asarray(target_xyz, dtype=np.float64).reshape(3)
    err_norm = float("inf")
    for _ in range(max_iters):
        T = forward_kinematics_matrix(q)
        err = target - T[:3, 3]
        err_norm = float(np.linalg.norm(err))
        if err_norm < tol_m:
            return IKResult(q=q, reachable=True, position_error_m=err_norm)
        J = _numerical_jacobian(q)[:3, :]
        JJt = J @ J.T + _IK_DAMPING * np.eye(3)
        dq = J.T @ np.linalg.solve(JJt, err)
        q = np.clip(q + dq, limits[:, 0], limits[:, 1])
    T = forward_kinematics_matrix(q)
    err_norm = float(np.linalg.norm(target - T[:3, 3]))
    return IKResult(q=q, reachable=err_norm < tol_m, position_error_m=err_norm)


class SO101Kinematics:
    """5-DOF SO-101 arm kinematics (:class:`fret.robots.protocols.KinematicsBackend`).

    The gripper (6th) joint is handled separately by the controller/grasp
    logic, mirroring :class:`OpenManipulatorXKinematics`.
    """

    @property
    def dof(self) -> int:
        """Arm degrees of freedom (gripper excluded)."""
        return 5

    @property
    def joint_names(self) -> list[str]:
        """SO-101 arm joint names, kinematic-chain order."""
        return list(_JOINT_NAMES)

    @property
    def joint_limits(self) -> npt.NDArray[np.float64]:
        """Joint limits ``(5, 2)`` lower/upper [rad], from the vendored MJCF."""
        return joint_limits_array()

    def forward_kinematics(
        self, joint_positions: npt.NDArray[np.float64]
    ) -> npt.NDArray[np.float64]:
        """Return the 4x4 ``gripperframe`` pose in the world frame."""
        return forward_kinematics_matrix(joint_positions)

    def jacobian(
        self, joint_positions: npt.NDArray[np.float64]
    ) -> npt.NDArray[np.float64]:
        """Return the finite-difference geometric Jacobian ``(6, 5)``."""
        return _numerical_jacobian(joint_positions)

    def inverse_kinematics(
        self,
        ee_pose: npt.NDArray[np.float64],
        seed: npt.NDArray[np.float64] | None = None,
    ) -> npt.NDArray[np.float64]:
        """Position IK (FR-SIM-17).

        Raises:
            UnreachablePoseError: When no configuration reaches
                ``ee_pose`` within tolerance (never a silently clipped
                best-effort result).
        """
        target = np.asarray(ee_pose, dtype=np.float64)
        target_xyz = (
            target[:3, 3] if target.shape == (4, 4) else target.reshape(-1)[:3]
        )
        result = solve_ik(target_xyz, seed=seed)
        if not result.reachable:
            raise UnreachablePoseError(
                f"SO-101 IK did not converge to {target_xyz.tolist()} "
                f"(final error {result.position_error_m:.4f} m)"
            )
        return result.q
